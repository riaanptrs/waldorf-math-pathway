// Generate a reviewable, idempotent data-only catalogue update. No learner data.
const fs = require('node:fs');
const path = require('node:path');
const {root, lessons} = require('./load-catalogue.cjs')();
const quote = text => `'${String(text).replace(/'/g, "''")}'`;
function build(maxGrade = 9) {
const selected = lessons.filter(lesson => Number(lesson.grade.slice(6)) <= maxGrade);
const positions = {};
const values = selected.map(lesson => {
  const grade = Number(lesson.grade.slice(6));
  const position = 1000 + (positions[grade] = (positions[grade] || 0) + 1);
  return `  (${quote(lesson.activityKey)}, ${grade}, ${position}, ${quote('Math: ' + lesson.title)}, ${quote('https://riaanptrs.github.io/waldorf-math-pathway/#practice:' + lesson.id)}, false, true)`;
});
return `-- Generated by scripts/build-math-catalogue.cjs; ${selected.length} math activities.
-- Requires the Grades 1–9 check already defined in migration 20260815120000.
-- New entries use reserved positions above 1000, avoiding shared English entries.
-- Existing positions, activity keys, learner records and RLS remain intact.
with registered as (
insert into public.course_activities (activity_key, unit_number, unit_position, title, path, is_portfolio, is_active)
values
${values.join(',\n')}
on conflict (activity_key) do update
set title = excluded.title, path = excluded.path, is_active = excluded.is_active
returning activity_key
)
select count(*) as registered_math_activities from registered;
`;
}
module.exports = {build};
if (require.main === module) {
const output = path.join(root, 'supabase', 'seeds', 'math-catalogue.sql');
fs.mkdirSync(path.dirname(output), {recursive:true});
fs.writeFileSync(output, build());
console.log(`Generated ${lessons.length} activity registrations in supabase/seeds/math-catalogue.sql`);
}
